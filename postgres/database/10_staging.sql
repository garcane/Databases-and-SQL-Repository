-- ----------------------------------------------------------------------------
-- staging.categories                                        source: Categories
-- ----------------------------------------------------------------------------
CREATE TABLE staging.categories (
    category_id     integer       GENERATED BY DEFAULT AS IDENTITY,
    category_name   varchar(15)   NOT NULL,
    description     text          NULL,
    picture         bytea         NULL,

    CONSTRAINT pk_categories PRIMARY KEY (category_id)
);

COMMENT ON TABLE staging.categories IS 'Port of dbo.Categories.';

-- ----------------------------------------------------------------------------
-- staging.customers                                          source: Customers
--
-- The natural key is a 5-character alphabetic code (e.g. 'ALFKI'), not an
-- integer. char(5) is retained rather than "improved" to varchar so that the
-- blank-padding semantics of the source are reproduced exactly.
-- ----------------------------------------------------------------------------
CREATE TABLE staging.customers (
    customer_id     char(5)       NOT NULL,
    company_name    varchar(40)   NOT NULL,
    contact_name    varchar(30)   NULL,
    contact_title   varchar(30)   NULL,
    address         varchar(60)   NULL,
    city            varchar(15)   NULL,
    region          varchar(15)   NULL,
    postal_code     varchar(10)   NULL,
    country         varchar(15)   NULL,
    phone           varchar(24)   NULL,
    fax             varchar(24)   NULL,

    CONSTRAINT pk_customers PRIMARY KEY (customer_id)
);

COMMENT ON TABLE staging.customers IS 'Port of dbo.Customers.';

-- ----------------------------------------------------------------------------
-- staging.employees                                          source: Employees
--
-- Self-referencing hierarchy via reports_to. The source also carries
-- CK_Birthdate CHECK (BirthDate < getdate()).
--
-- That constraint CANNOT be ported. PostgreSQL requires CHECK expressions to be
-- immutable, and CURRENT_TIMESTAMP is stable, not immutable:
--
--     ERROR:  cannot use column reference in DEFAULT expression
--     ERROR:  functions in check constraint must be marked IMMUTABLE
--
-- SQL Server permits it, at the cost of a constraint whose truth value changes
-- with the clock and is never re-verified on existing rows. The rule is
-- enforced in tests/validation.sql instead, where it belongs.
-- ----------------------------------------------------------------------------
CREATE TABLE staging.employees (
    employee_id       integer       GENERATED BY DEFAULT AS IDENTITY,
    last_name         varchar(20)   NOT NULL,
    first_name        varchar(10)   NOT NULL,
    title             varchar(30)   NULL,
    title_of_courtesy varchar(25)   NULL,
    birth_date        timestamp(3)  NULL,
    hire_date         timestamp(3)  NULL,
    address           varchar(60)   NULL,
    city              varchar(15)   NULL,
    region            varchar(15)   NULL,
    postal_code       varchar(10)   NULL,
    country           varchar(15)   NULL,
    home_phone        varchar(24)   NULL,
    extension         varchar(4)    NULL,
    photo             bytea         NULL,
    notes             text          NULL,
    reports_to        integer       NULL,
    photo_path        varchar(255)  NULL,

    CONSTRAINT pk_employees PRIMARY KEY (employee_id)
);

COMMENT ON TABLE staging.employees IS
    'Port of dbo.Employees. CK_Birthdate is not portable (non-immutable '
    'expression) and is asserted in tests/validation.sql instead.';

