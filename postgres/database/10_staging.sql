-- ============================================================================
-- 10_staging.sql
--
-- Landing zone: a structural 1:1 port of the Northwind OLTP schema.
-- Run after 00_schemas.sql.
--
-- Source of truth: sqlserver/database/northwind/northwind.sql
-- Every table, column, order and nullability below matches that file. Names are
-- converted to snake_case; nothing is added, removed or reordered.
--
-- ----------------------------------------------------------------------------
-- Type mapping applied throughout (see docs/migration-guide.md)
-- ----------------------------------------------------------------------------
--   nvarchar(n)          ->  varchar(n)
--   nchar(n)             ->  char(n)
--   ntext                ->  text
--   image                ->  bytea
--   money                ->  numeric(19,4)     -- not PG `money`: that type is
--                                              -- locale-dependent and its
--                                              -- output changes with lc_monetary
--   bit                  ->  boolean
--   real                 ->  real              -- preserved; tightened in warehouse
--   datetime             ->  timestamp(3)      -- source carries no time zone
--   smallint             ->  smallint
--   int IDENTITY(1,1)    ->  integer GENERATED BY DEFAULT AS IDENTITY
--
-- Why BY DEFAULT and not ALWAYS in this layer: staging is loaded with the
-- source system's own key values. GENERATED ALWAYS rejects an explicit insert
-- unless every statement carries OVERRIDING SYSTEM VALUE. BY DEFAULT accepts
-- the source key and still generates one if omitted. The trade-off is that the
-- underlying sequence is not advanced by explicit inserts, so the seed scripts
-- in postgres/seed/ reset it with setval() after loading. Warehouse surrogate
-- keys use GENERATED ALWAYS, where nothing outside ETL may supply a value.
--
-- ----------------------------------------------------------------------------
-- Constraint policy in this layer
-- ----------------------------------------------------------------------------
-- Primary keys are kept: they are the declared grain of each source table, and
-- a duplicate arriving here is a genuine extract failure worth stopping on.
--
-- Foreign keys and CHECK constraints are deliberately NOT carried over. A
-- landing zone that rejects rows loses the very evidence needed to diagnose an
-- upstream problem. Referential integrity and domain rules are asserted instead
-- by tests/validation.sql, which reports violations as data rather than
-- aborting the load.
-- ============================================================================

