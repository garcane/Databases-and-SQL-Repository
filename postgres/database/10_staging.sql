-- ----------------------------------------------------------------------------
-- staging.products                                            source: Products
--
-- Source CHECK constraints (UnitPrice >= 0, UnitsInStock >= 0, UnitsOnOrder >= 0,
-- ReorderLevel >= 0) are portable verbatim but are held back to the warehouse
-- layer per the constraint policy above.
-- ----------------------------------------------------------------------------
CREATE TABLE staging.products (
    product_id        integer        GENERATED BY DEFAULT AS IDENTITY,
    product_name      varchar(40)    NOT NULL,
    supplier_id       integer        NULL,
    category_id       integer        NULL,
    quantity_per_unit varchar(20)    NULL,
    unit_price        numeric(19,4)  NULL DEFAULT 0,
    units_in_stock    smallint       NULL DEFAULT 0,
    units_on_order    smallint       NULL DEFAULT 0,
    reorder_level     smallint       NULL DEFAULT 0,
    discontinued      boolean        NOT NULL DEFAULT false,

    CONSTRAINT pk_products PRIMARY KEY (product_id)
);

COMMENT ON TABLE staging.products IS 'Port of dbo.Products.';
COMMENT ON COLUMN staging.products.discontinued IS
    'bit -> boolean. Source stores 0/1; the seed scripts cast on load.';

