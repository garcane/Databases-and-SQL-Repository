-- ----------------------------------------------------------------------------
-- staging.order_details                                 source: Order Details
--
-- The source table name contains a space and is referenced throughout the
-- reference implementation as [Order Details]. The port renames it to
-- order_details: snake_case removes the need for quoted identifiers entirely,
-- which is the single most common cause of breakage when T-SQL is moved to a
-- case-sensitive-when-quoted engine.
-- ----------------------------------------------------------------------------
CREATE TABLE staging.order_details (
    order_id     integer        NOT NULL,
    product_id   integer        NOT NULL,
    unit_price   numeric(19,4)  NOT NULL DEFAULT 0,
    quantity     smallint       NOT NULL DEFAULT 1,
    discount     real           NOT NULL DEFAULT 0,

    CONSTRAINT pk_order_details PRIMARY KEY (order_id, product_id)
);

COMMENT ON TABLE staging.order_details IS
    'Port of [dbo].[Order Details]. Grain: one row per product per order.';

