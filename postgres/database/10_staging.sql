-- ----------------------------------------------------------------------------
-- Extract-side indexes
--
-- The reference implementation carries 30 indexes, several of them exact
-- duplicates created under different names (CustomerID and CustomersOrders on
-- Orders(CustomerID); CategoryID and CategoriesProducts on Products(CategoryID);
-- and so on - eight duplicated pairs in total).
--
-- They are not reproduced. Staging is written once per load and read once per
-- load, in full-table passes; secondary indexes would slow the write and never
-- be used by the read. The duplicates are catalogued in docs/migration-guide.md
-- as a finding, not carried forward as a feature.
--
-- Only the extract-ordering index below earns its place: the dimension loaders
-- probe staging.orders by customer to build SCD2 change sets.
-- ----------------------------------------------------------------------------
CREATE INDEX ix_staging_orders_customer_date
    ON staging.orders (customer_id, order_date);
